import { twoFactorCode, type Me } from '@app/contracts/identity';
import { useState, type FormEvent } from 'react';
import { Navigate, useNavigate, useSearchParams } from 'react-router';
import { useMe } from '../../../shared/api/me';
import { Badge, Button, ErrorState, Field, Input, Spinner } from '../../../shared/ui';
import { useCommitMe, useLogout, useTwoFactorSetup, useTwoFactorVerify } from '../api/hooks';
import { CodeInput } from '../components/code-input';
import { FormError } from '../components/form-error';
import { copy, fill } from '../copy';
import { isApiError } from '../lib/form-errors';
import { safeNext } from '../lib/next';

type Problem = 'wrong' | 'tooMany' | 'expired' | 'other' | null;

const problemText: Record<Exclude<Problem, null>, string> = {
  wrong: copy.twoFactor.wrong,
  tooMany: copy.twoFactor.tooMany,
  expired: copy.twoFactor.expired,
  other: copy.common.network,
};

/** Runs the code submit: validates the digits, then maps API errors to inline text. */
function useCodeSubmit() {
  const navigate = useNavigate();
  const [params] = useSearchParams();
  const commitMe = useCommitMe();
  const verify = useTwoFactorVerify();
  const [problem, setProblem] = useState<Problem>(null);

  const submit = async (rawCode: string) => {
    const code = rawCode.replace(/\D/g, '');
    if (!twoFactorCode.safeParse(code).success) {
      setProblem('wrong');
      return;
    }
    setProblem(null);
    try {
      const me = await verify.mutateAsync(code);
      commitMe(me);
      await navigate(destination(me, safeNext(params.get('next'))), { replace: true });
    } catch (error) {
      if (isApiError(error, 401, 'INVALID_CODE')) setProblem('wrong');
      else if (isApiError(error, 429)) setProblem('tooMany');
      else if (isApiError(error, 401)) setProblem('expired');
      else setProblem('other');
    }
  };
  return { submit, problem, pending: verify.isPending };
}

function destination(me: Me, next: string | null): string {
  return next ?? (me.member.isStaff ? '/staff' : '/');
}

function Heading({ title, subtitle }: { title: string; subtitle: string }) {
  return (
    <header className="flex flex-col gap-1.5">
      <Badge className="self-start">{copy.twoFactor.staff}</Badge>
      <h2 className="m-0 text-[22px] font-semibold text-fg">{title}</h2>
      <p className="m-0 text-sm text-muted">{subtitle}</p>
    </header>
  );
}

function CodeEntry({ email }: { email: string }) {
  const { submit, problem, pending } = useCodeSubmit();
  const [code, setCode] = useState('');
  const logout = useLogout();
  const navigate = useNavigate();

  const onSubmit = (event: FormEvent) => {
    event.preventDefault();
    void submit(code);
  };

  const otherAccount = () =>
    logout.mutate(undefined, { onSettled: () => void navigate('/login', { replace: true }) });

  return (
    <div className="flex flex-col gap-5">
      <Heading title={copy.twoFactor.title} subtitle={fill(copy.twoFactor.subtitle, { email })} />
      <form onSubmit={onSubmit} className="flex flex-col gap-4">
        <CodeInput value={code} onChange={setCode} invalid={problem === 'wrong'} disabled={pending} />
        {problem && <FormError>{problemText[problem]}</FormError>}
        <Button type="submit" variant="primary" size="lg" loading={pending}>
          {copy.twoFactor.submit}
        </Button>
      </form>
      <Button variant="ghost" onClick={otherAccount}>
        {copy.twoFactor.otherAccount}
      </Button>
    </div>
  );
}

function groupKey(secret: string): string {
  return secret.replace(/\s/g, '').replace(/(.{4})/g, '$1 ').trim();
}

function SetupEntry() {
  const setup = useTwoFactorSetup(true);
  const { submit, problem, pending } = useCodeSubmit();
  const [code, setCode] = useState('');

  if (setup.isPending) {
    return (
      <div className="grid place-items-center py-10">
        <Spinner label={copy.twoFactor.setupLoading} />
      </div>
    );
  }
  if (setup.isError) {
    return (
      <ErrorState
        title={copy.twoFactor.setupError}
        onRetry={() => void setup.refetch()}
      />
    );
  }

  const onSubmit = (event: FormEvent) => {
    event.preventDefault();
    void submit(code);
  };

  return (
    <div className="flex flex-col gap-5">
      <Heading title={copy.twoFactor.setupTitle} subtitle={copy.twoFactor.setupSubtitle} />
      <div
        role="img"
        aria-label={copy.twoFactor.qrLabel}
        className="mx-auto size-48 rounded-row bg-white p-2 [&_svg]:size-full"
        // The SVG is generated by our own API from the otpauth URL (qrcode library).
        dangerouslySetInnerHTML={{ __html: setup.data.qrSvg }}
      />
      <ol className="m-0 flex list-decimal flex-col gap-3 pl-5 text-sm text-fg-2">
        <li>{copy.twoFactor.stepScan}</li>
        <li>
          {copy.twoFactor.stepKey}{' '}
          <span className="font-mono text-fg">{groupKey(setup.data.secret)}</span>
        </li>
      </ol>
      <form onSubmit={onSubmit} noValidate className="flex flex-col gap-4">
        <Field label={copy.twoFactor.stepCode} error={problem === 'wrong' ? problemText.wrong : undefined}>
          {(p) => (
            <Input
              {...p}
              inputMode="numeric"
              autoComplete="one-time-code"
              value={code}
              onChange={(e) => setCode(e.target.value)}
              className="font-mono"
            />
          )}
        </Field>
        {problem && problem !== 'wrong' && <FormError>{problemText[problem]}</FormError>}
        <Button type="submit" variant="primary" size="lg" loading={pending}>
          {copy.twoFactor.setupSubmit}
        </Button>
      </form>
    </div>
  );
}

/** FR-5: the code step of a Staff sign-in, or the QR setup on the first one. */
export function TwoFactorPage() {
  const { me, isLoading, isSignedOut, error, refetch } = useMe();
  const [params] = useSearchParams();

  if (isLoading) {
    return (
      <div className="grid place-items-center py-10">
        <Spinner />
      </div>
    );
  }
  if (isSignedOut) return <Navigate to="/login" replace />;
  if (error || !me) return <ErrorState onRetry={refetch} />;
  if (!me.twoFactor.required || me.twoFactor.passed) {
    return <Navigate to={destination(me, safeNext(params.get('next')))} replace />;
  }
  return me.twoFactor.setUp ? <CodeEntry email={me.member.email} /> : <SetupEntry />;
}
